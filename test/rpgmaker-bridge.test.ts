// The RPG Maker bridge: installing the plugin into MV and MZ game folders (and taking it out
// exactly), and the plugin itself running against a real Telos hub, with stand-ins for the
// RPG Maker objects it uses.

const root = path.resolve(import.meta.dirname, "..");
const PLUGIN = path.join(root, "bridge-rpgmaker", "TelosBridge.js");

const PLUGINS_JS = `// Generated by RPG Maker.
// Do not edit this file directly.
var $plugins =
[
{"name":"YEP_CoreEngine","status":true,"description":"Core","parameters":{"Screen Width":"816"}},
{"name":"Community_Basic","status":false,"description":"Basic","parameters":{}}
];
`;

function fakeRpgMaker(layout: "mv" | "mz") {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "telos-rpgm-"));
  const dirs: UserDirs = { home: path.join(tmp, "home"), appData: path.join(tmp, "a"), localAppData: path.join(tmp, "l") };
  const install = path.join(tmp, "HeroQuest");
  const base = layout === "mv" ? path.join(install, "www") : install;
  fs.mkdirSync(path.join(base, "data"), { recursive: true });
  fs.mkdirSync(path.join(base, "js", "plugins"), { recursive: true });
  fs.writeFileSync(path.join(base, "data", "System.json"), JSON.stringify({ gameTitle: "Hero Quest" }));
  fs.writeFileSync(path.join(base, "js", "plugins.js"), PLUGINS_JS);
  fs.writeFileSync(path.join(base, "js", "plugins", "YEP_CoreEngine.js"), "// core");
  fs.writeFileSync(path.join(install, "Game.exe"), "");
  return { install, base, profile: buildProfile(path.join(install, "Game.exe"), dirs) };
}

test("installs into an MV game (www/) and comes out exactly, keeping the player's plugins", () => {
  const { install, base, profile } = fakeRpgMaker("mv");
  assert.equal(profile.engine, "RPG Maker MV/MZ");
  assert.deepEqual(rpgMakerBridgeState(profile, PLUGIN), { supported: true, installed: false });

  const report = installRpgMakerBridge(profile, { pluginJs: PLUGIN, port: 7788 });
  assert.equal(report.updated, false);
  assert.deepEqual(report.files, ["www/js/plugins/TelosBridge.js"]);
  assert.equal(fs.readFileSync(path.join(base, "js", "plugins", "TelosBridge.js"), "utf8"), fs.readFileSync(PLUGIN, "utf8"));
  const list = readPlugins(path.join(base, "js", "plugins.js"));
  assert.deepEqual(list.list.map((p) => p.name), ["YEP_CoreEngine", "Community_Basic", "TelosBridge"]);
  assert.equal(list.list[2].parameters.HubUrl, "ws://127.0.0.1:7788/ws/adapter");
  assert.match(list.head, /Generated by RPG Maker/);
  assert.deepEqual(rpgMakerBridgeState(profile, PLUGIN), { supported: true, installed: true });

  // Installing again (an update after the game quit, no port given) keeps one entry and the address.
  assert.equal(installRpgMakerBridge(profile, { pluginJs: PLUGIN }).updated, true);
  const again = readPlugins(path.join(base, "js", "plugins.js")).list;
  assert.equal(again.filter((p) => p.name === "TelosBridge").length, 1);
  assert.equal(again.at(-1)!.parameters.HubUrl, "ws://127.0.0.1:7788/ws/adapter");

  // The player turns on another plugin meanwhile: removal keeps that.
  const parts = readPlugins(path.join(base, "js", "plugins.js"));
  parts.list[1].status = true;
  fs.writeFileSync(path.join(base, "js", "plugins.js"), parts.head + JSON.stringify(parts.list) + parts.tail);

  assert.deepEqual(removeRpgMakerBridge(profile), { removed: 2 });
  const after = readPlugins(path.join(base, "js", "plugins.js")).list;
  assert.deepEqual(after.map((p) => [p.name, p.status]), [["YEP_CoreEngine", true], ["Community_Basic", true]]);
  assert.ok(!fs.existsSync(path.join(base, "js", "plugins", "TelosBridge.js")));
  assert.ok(fs.existsSync(path.join(base, "js", "plugins", "YEP_CoreEngine.js")));
  assert.deepEqual(fs.readdirSync(install).sort(), ["Game.exe", "www"], "no manifest or backup left behind");
  assert.deepEqual(fs.readdirSync(path.join(base, "js")).sort(), ["plugins", "plugins.js"]);
  assert.throws(() => removeRpgMakerBridge(profile), /isn't installed/);
});

test("MZ keeps js/ at the top; an outdated plugin is spotted", () => {
  const { base, profile } = fakeRpgMaker("mz");
  installRpgMakerBridge(profile, { pluginJs: PLUGIN, port: 7777 });
  assert.ok(fs.existsSync(path.join(base, "js", "plugins", "TelosBridge.js")));
  fs.writeFileSync(path.join(base, "js", "plugins", "TelosBridge.js"), "// an older bridge");
  assert.equal(rpgMakerBridgeState(profile, PLUGIN).outdated, true);
});

test("refuses a hand-edited plugin list and packed games, without writing anything", () => {
  const { install, base, profile } = fakeRpgMaker("mz");
  fs.writeFileSync(path.join(base, "js", "plugins.js"), "var $plugins = [ {name: 'NotJson'} ];");
  assert.throws(() => installRpgMakerBridge(profile, { pluginJs: PLUGIN }), /edited by hand/);
  assert.ok(!fs.existsSync(path.join(base, "js", "plugins", "TelosBridge.js")));
  assert.deepEqual(fs.readdirSync(install).sort(), ["Game.exe", "data", "js"]);

  fs.rmSync(path.join(base, "js", "plugins.js"));
  const state = rpgMakerBridgeState(profile);
  assert.equal(state.supported, false);
  assert.match(state.reason!, /packed/);
});

